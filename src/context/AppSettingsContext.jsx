export const AppSettingsProvider = ({ children }) => {
  const [theme, setTheme] = useState(() => {
    try {
      return localStorage.getItem('bir-kadam-theme') || 'dark'
    } catch {
      return 'dark'
    }
  })

  const [language, setLanguage] = useState(() => {
    try {
      const savedLanguage = localStorage.getItem('bir-kadam-language')
      return ['ky', 'ru', 'en'].includes(savedLanguage) ? savedLanguage : 'ru'
    } catch {
      return 'ru'
    }
  })

  useEffect(() => {
    document.body.classList.toggle('theme-dark', theme === 'dark')
    document.body.classList.toggle('theme-light', theme === 'light')
    document.documentElement.lang = language
    document.title = pageTitles[language]

    try {
      localStorage.setItem('bir-kadam-theme', theme)
    } catch {
      // ignore storage errors in private or restricted contexts
    }
  }, [theme, language])

  useEffect(() => {
    try {
      localStorage.setItem('bir-kadam-language', language)
    } catch {
      // ignore storage errors in private or restricted contexts
    }
  }, [language])

  const t = useCallback((path, fallback = '') => {
    const keys = path.split('.')
    const localeData = translations[language] || translations.ru
    const resolve = (source) => {
      let result = source

      for (const key of keys) {
        if (!result || typeof result !== 'object' || !(key in result)) {
          return undefined
        }
        result = result[key]
      }

      return typeof result === 'string' ? result : undefined
    }

    return resolve(localeData) || resolve(translations.ru) || fallback || path
  }, [language])

  const value = useMemo(
    () => ({
      theme,
      setTheme,
      language,
      setLanguage,
      t,
    }),
    [language, theme, t],
  )

  return <AppSettingsContext.Provider value={value}>{children}</AppSettingsContext.Provider>
}

export const useAppSettings = () => {
  const context = useContext(AppSettingsContext)

  if (!context) {
    throw new Error('useAppSettings must be used within AppSettingsProvider')
  }

  return context
}
